#!/usr/bin/env bash
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/build-metadata.sh
. "$SCRIPT_DIR/lib/build-metadata.sh"
ANDROID_VARIANT="$(android_build_variant "${ANDROID_BATCH_BUILD:-0}" "${SUPPORTED_ANDROID_VERSIONS:-}")"
SAFE_KERNEL_BRANCH="${KERNEL_BRANCH//\//-}"
BUILD_TIMESTAMP="$(date -u +'%Y%m%d_%H%M%S')"
ARTIFACT_NAME="kernel-package-${GITHUB_RUN_ID}-${GITHUB_RUN_ATTEMPT}-${KSU_TYPE}${ANDROID_VARIANT:+-${ANDROID_VARIANT}}"
DIAGNOSTICS_NAME="kernel-diagnostics-${GITHUB_RUN_ID}-${GITHUB_RUN_ATTEMPT}-${KSU_TYPE}${ANDROID_VARIANT:+-${ANDROID_VARIANT}}"
CCACHE_KEY_PREFIX="${RUNNER_OS}-ccache-v2-${SOC}-${SOURCE_SLUG}-${PROFILE_ID}-${SAFE_KERNEL_BRANCH}-${CLANG_VERSION}-${KSU_TYPE}-${ROM_GKI_MODULE_COMPAT}"
CCACHE_EPOCH="$(date -u +'%G-W%V')"
{
  echo "BUILD_TIMESTAMP=${BUILD_TIMESTAMP}"
  echo "SAFE_KERNEL_BRANCH=${SAFE_KERNEL_BRANCH}"
  echo "ARTIFACT_NAME=${ARTIFACT_NAME}"
  echo "DIAGNOSTICS_NAME=${DIAGNOSTICS_NAME}"
  echo "CCACHE_KEY_PREFIX=${CCACHE_KEY_PREFIX}"
  echo "CCACHE_KEY=${CCACHE_KEY_PREFIX}-${CCACHE_EPOCH}-${GITHUB_RUN_ID}-${GITHUB_RUN_ATTEMPT}"
} >> "$GITHUB_ENV"
echo "artifact_name=${ARTIFACT_NAME}" >> "$GITHUB_OUTPUT"
